"""Build Unlimited Crafting Storage Range for Recompia (a Modtopia code mod) into
dist/recompia_unlimited_crafting_storage_range-<version>.pkmod (+ .sha256, + a .zip with the README).

Usage:  py recompia\\unlimited-crafting-storage-range\\build.py [--zig PATH] [--clang PATH]

Writes mod.toml, compiles src/unlimited_crafting_storage_range.c for windows-x64 (mod.dll) and linux-x64 (mod.so), and
packs mod.toml + bin/ into the .pkmod (a zip). The compilers are found as in ../play-as-pokemon/build.py, whose helpers
this uses: zig (--zig, ZIG, PATH; Recompia ships one at <install>/tools/build/zig/zig.exe), and for the Linux library
clang + ld.lld when that zig has no Linux headers (--clang, CLANG, PATH; llvm-mingw works).
"""
import argparse, importlib.util, os, shutil, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DIST = os.path.join(REPO, 'dist')
PAP = os.path.join(REPO, 'recompia', 'play-as-pokemon')

MOD_ID = 'unlimited_crafting_storage_range'
VERSION = '1.0.0'
OUT_NAME = f'recompia_{MOD_ID}-{VERSION}'

HOOKS = [
    ('scan_local', 0x7504F0, 0x97EC1E55, 'bl right after the station\'s own scan: station x19'),
    ('scan_shared', 0x7505E8, 0xAA1403E0, 'mov x0, x20 right after the scan for a station in use: station x20, flag w21, player w19'),
    ('range_count', 0x5B1C84, 0xD503237F, 'slot range for counting (entry): w1 kind, w2 index, x4 *start, x5 *count'),
    ('range_take', 0x2EE4BC, 0xD503237F, 'slot range for checking and taking (entry): w0 kind, w1 index, x2 *start, x3 *count'),
]

DESCRIPTION = (
    "Crafting stations use the items in every storage box, chest and crate you have placed, at any distance, not only "
    "the boxes right next to them. Crafting takes the materials from whichever box holds them, and from your bag if "
    "the boxes run short. No buttons. The Pokopia Editor's Unlimited Crafting Storage Range mod, made for Recompia.")


def load_pap_build():
    spec = importlib.util.spec_from_file_location('pap_build', os.path.join(PAP, 'build.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def write_mod_toml(pap):
    L = [
        '# Generated by build.py: edit it there.',
        f'id = "{MOD_ID}"',
        'name = "Unlimited Crafting Storage Range"',
        f'version = "{VERSION}"',
        'authors = ["cycalo"]',
        f'description = {pap.toml_str(DESCRIPTION)}',
        'license = "GPL-3.0-or-later"',
        'homepage = "https://github.com/cycalo/Pokopia-Editor"',
        'loader = ">=0.6.0 <1.0.0"',
        'game = ["2.0.1"]',
        'affects = "gameplay"',
        '',
        '# Every code patch of the emulator version (an IPS for main build 76a489f3bd3642fa), as a take_over point.',
    ]
    for name, off, word, what in HOOKS:
        L += ['', '[[hooks."2.0.1"]]', f'name = "{name}"   # {what}', f'target = "main+{off:#x}"', f'word = {word:#010x}',
              'kind = "take_over"']
    with open(os.path.join(HERE, 'mod.toml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


def build_linux_with_clang(pap, clang, flags, src, dst):
    work = os.path.join(HERE, 'build', 'linux-sdk')
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(os.path.join(work, 'include'))
    for name, text in pap.LINUX_SHIM.items():
        with open(os.path.join(work, 'include', name), 'w', encoding='ascii', newline='\n') as f:
            f.write(text)
    for name, text in (('libc_stub.c', pap.LIBC_STUB), ('libc.map', pap.LIBC_VERSIONS)):
        with open(os.path.join(work, name), 'w', encoding='ascii', newline='\n') as f:
            f.write(text)
    libc = os.path.join(work, 'libc.so.6')
    base = [clang, '-target', 'x86_64-linux-gnu', '-ffreestanding', '-nostdlib', '-shared', '-fPIC', '-fuse-ld=lld']
    cmds = [base + ['-Wl,-soname,libc.so.6', '-Wl,--version-script,' + os.path.join(work, 'libc.map'), '-o', libc,
                    os.path.join(work, 'libc_stub.c')],
            base + [*flags, '-nostdlibinc', '-isystem', os.path.join(work, 'include'), '-fvisibility=hidden',
                    '-Wl,--no-undefined', '-Wl,-z,now', '-Wl,-z,relro', '-o', dst, src, libc]]
    for cmd in cmds:
        print(' '.join(cmd))
        if subprocess.run(cmd).returncode:
            return False
    return True


def compile_all(pap, zig, clang, out):
    src = os.path.join(HERE, 'src', f'{MOD_ID}.c')
    flags = ['-std=c11', '-O2', '-Wall', '-Wextra', '-Wno-unused-parameter', '-Werror', '-I', os.path.join(PAP, 'include')]
    targets = [('windows-x64', 'x86_64-windows-gnu', 'mod.dll', []),
               ('linux-x64', 'x86_64-linux-gnu', 'mod.so', ['-fPIC', '-fvisibility=hidden'])]
    built = []
    for plat, triple, lib, extra in targets:
        d = os.path.join(out, 'bin', plat)
        os.makedirs(d, exist_ok=True)
        dst = os.path.join(d, lib)
        cmd = [zig, 'cc', '-target', triple, '-shared', *flags, *extra, '-o', dst, src]
        print(' '.join(cmd))
        if subprocess.run(cmd).returncode:
            if plat != 'linux-x64':
                sys.exit(f'the {plat} build failed')
            print('note: this zig cannot build the Linux library (no Linux headers); trying clang + lld')
            if not clang:
                sys.exit('no clang with ld.lld for the Linux library: pass --clang PATH (any LLVM, e.g. llvm-mingw)')
            if not build_linux_with_clang(pap, clang, flags, src, dst):
                sys.exit('the linux-x64 build failed')
        for junk in ('mod.lib', 'mod.pdb', f'{MOD_ID}.lib'):
            p = os.path.join(d, junk)
            if os.path.exists(p):
                os.remove(p)
        built.append(f'bin/{plat}/{lib}')
    return built


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--zig')
    ap.add_argument('--clang', help='clang with ld.lld beside it, for the Linux library when zig has no Linux headers')
    a = ap.parse_args()
    pap = load_pap_build()
    write_mod_toml(pap)
    stage = os.path.join(HERE, 'build', 'stage')
    shutil.rmtree(stage, ignore_errors=True)
    os.makedirs(stage)
    shutil.copy(os.path.join(HERE, 'mod.toml'), stage)
    files = ['mod.toml'] + compile_all(pap, pap.find_zig(a.zig), pap.find_clang(a.clang), stage)
    os.makedirs(DIST, exist_ok=True)
    out = os.path.join(DIST, OUT_NAME + '.pkmod')
    sha = pap.pack(stage, files, out)
    with open(out + '.sha256', 'w', encoding='ascii', newline='\n') as f:
        f.write(f'{sha}  {os.path.basename(out)}\n')
    # the download for people who want the README with it
    with zipfile.ZipFile(os.path.join(DIST, OUT_NAME + '.zip'), 'w', zipfile.ZIP_DEFLATED) as z:
        z.write(out, os.path.basename(out))
        z.write(out + '.sha256', os.path.basename(out) + '.sha256')
        z.write(os.path.join(HERE, 'README.md'), 'README.md')
    print(out)
    print('sha256', sha)


if __name__ == '__main__':
    main()
