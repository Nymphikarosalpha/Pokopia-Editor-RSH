"""Add the Pokemon abilities to the emulator / Switch build of Play as Pokemon (mods/play-as-pokemon/files).

  py mods\\play-as-pokemon\\src\\build_abilities.py --llvm DIR_WITH_clang_ld.lld_llvm-objcopy

1. Writes abilities_table.h: which ability each Pokemon has (3 bits a character-definition id), from the lists the Recompia
   build uses (recompia/play-as-pokemon/build.py, ABILITY_POKEMON).
2. Compiles abilities.c for AArch64 and links it at the end of main's code, right after the patch's A-Z table, where the
   unpatched main has zero padding up to its read-only data (main+0x274A000). Game addresses are absolute symbols the
   linker resolves PC-relative (adrp / bl), so the code runs wherever main is loaded; the object file may only hold such
   relocations, and the result may only have code and read-only data.
3. Rewrites the IPS: the player update's hook (main+0x2FACE0) now calls ability_entry, which runs the abilities and then
   jumps to the old hook target. The code goes in as one more record.
4. Adds the cheat that tells the code ZL + D-pad Down is held (u8 main+0x3D14C1D) to both cheat files.

Run it after re/build/build_v09.py (which writes the A-Z table and the cheats); running it twice gives the same files.
"""
import argparse, importlib.util, json, os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(MOD))
FILES = os.path.join(MOD, 'files')
IPS_NAME = '76A489F3BD3642FA5E18BD83D32C98BACC5F7D0E.ips'
CHEATS = ['76A489F3BD3642FA.txt', '76A489F3BD3642FA.any.txt']

TABLE, RO_START, HOOK = 0x2749480, 0x274A000, 0x2FACE0
CODE_AT, CODE_END = TABLE, 0x2749C00   # the end of main's code; Unlimited Crafting Storage Range's patch starts at 0x2749C00
AZ_AT, AZ_END = 0x3229E00, 0x322A000   # padding after main's read-only data (it ends at 0x3229DF4): the packed A to Z list
AZ_RAM, SELF_AT = 0x3D14D00, 0x35618F0  # the unpacked list (FLAG+0x100); the cheat's base pointer [main+0x3483AB8] = main+SELF_AT
OLD_CHEAT_BASE = '78021000 00E18472'    # build_v09: R2 = [base] - (SELF_AT - TABLE + 2), the list at TABLE
TICK_NEXT = 0x2A86A4   # the patch's per-frame hook program (build_v07.py) that main+0x2FACE0 called before the abilities
FLAG = 0x3D14C00
SYMBOLS = {
    'G_PLAYER': 0x3561928, 'G_ENTITIES': 0x356A778, 'G_FIELD': 0x35616F8, 'G_OBJECTS': 0x35616F0, 'G_WORLD': 0x34EFC98,
    'G_GAMEMGR': 0x3561710, 'FLAG': FLAG,
    'fn_grow': 0x1F1200, 'fn_object_act': 0x77CEA0, 'fn_water': 0x3694C0, 'fn_bubble': 0x5A60E0, 'fn_has_layer': 0x38DF8,
}
ABILITIES = ['Grow', 'Burn', 'Water', 'Generate']   # the order of AB_* in abilities.c
# relocations a main-relative, position-independent result may use
PC_RELATIVE = {'R_AARCH64_ADR_PREL_PG_HI21', 'R_AARCH64_ADD_ABS_LO12_NC', 'R_AARCH64_CALL26', 'R_AARCH64_JUMP26',
               'R_AARCH64_CONDBR19', 'R_AARCH64_TSTBR14', 'R_AARCH64_ADR_PREL_LO21', 'R_AARCH64_LD_PREL_LO19'} | \
              {f'R_AARCH64_LDST{n}_ABS_LO12_NC' for n in (8, 16, 32, 64, 128)}
CHEAT_NAME = 'Ability - ZR or ZL+Down uses the Pokemon ability'
CHEAT = [f'[{CHEAT_NAME}]', '400F0000 00000000 00000000', f'010F0000 {FLAG + 0x1D:08X} 00000000',
         '80008100', f'010F0000 {FLAG + 0x1D:08X} 00000001', '20000000', '']


def ability_lists():
    spec = importlib.util.spec_from_file_location('recompia_build', os.path.join(REPO, 'recompia', 'play-as-pokemon', 'build.py'))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    assert m.ABILITIES == ABILITIES, 'the ability order must match'
    return m.ABILITY_POKEMON


def write_table():
    with open(os.path.join(MOD, 'pokemon.json'), encoding='utf-8') as f:
        pokemon = {k.replace('’', "'"): v for k, v in json.load(f).items()}
    kinds = {}
    for kind, ab in enumerate(ABILITIES):
        for name in ability_lists()[ab].split():
            assert name in pokemon, name
            kinds[pokemon[name]] = kind + 1
    order = sorted(pokemon, key=str.lower)   # the cheat's A to Z order (build_v09.py, the Recompia build)
    az = [pokemon[k] for k in order]
    assert max(az) < 512
    packed = bytearray((len(az) * 9 + 7) // 8 + 2)
    for i, v in enumerate(az):
        packed[i * 9 // 8] |= (v << (i * 9 % 8)) & 0xFF
        packed[i * 9 // 8 + 1] |= (v << (i * 9 % 8)) >> 8 & 0xFF
        packed[i * 9 // 8 + 2] |= (v << (i * 9 % 8)) >> 16 & 0xFF
    assert AZ_AT + len(packed) <= AZ_END
    n = max(kinds) + 1
    bits = bytearray((n * 3 + 7) // 8 + 2)   # +2: the reader looks at the next byte too
    for i, v in kinds.items():
        bits[i * 3 // 8] |= (v << (i * 3 % 8)) & 0xFF
        bits[i * 3 // 8 + 1] |= v << (i * 3 % 8) >> 8
    body = ', '.join(f'0x{b:02x}' for b in bits)
    with open(os.path.join(HERE, 'abilities_table.h'), 'w', newline='\n') as f:
        f.write('/* Generated by build_abilities.py: do not edit. 3 bits a character-definition id: 0 none, 1 + AB_* */\n'
                f'static const u8 ABILITY_BITS[{len(bits)}] = {{{body}}};\n'
                f'#define AZ_COUNT {len(az)}u   /* entries in the A to Z list */\n')
    return len(kinds), bytes(packed), len(az)


def read_ips(d):
    if d[:5] == b'PATCH':
        i, w, eof = 5, 3, b'EOF'
    else:
        assert d[:5] == b'IPS32'
        i, w, eof = 5, 4, b'EEOF'
    out = []
    while d[i:i + w] != eof:
        off, n = int.from_bytes(d[i:i + w], 'big'), int.from_bytes(d[i + w:i + w + 2], 'big')
        out.append((off - 0x100, d[i + w + 2:i + w + 2 + n]))
        i += w + 2 + n
    return out


def write_ips32(recs):
    o = bytearray(b'IPS32')
    for off, data in sorted(recs):
        assert len(data) < 0x10000
        o += (off + 0x100).to_bytes(4, 'big') + len(data).to_bytes(2, 'big') + data
    return bytes(o + b'EEOF')


def bl(pc, target):
    d = (target - pc) >> 2
    assert -(1 << 25) <= d < (1 << 25)
    return 0x94000000 | (d & 0x3FFFFFF)


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(' '.join(cmd) + '\n' + r.stdout + r.stderr)
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--llvm', required=True, help='folder with clang, ld.lld, llvm-objcopy, llvm-objdump')
    a = ap.parse_args()
    tool = lambda n: os.path.join(a.llvm, n + ('.exe' if os.name == 'nt' else ''))
    count, packed, n_az = write_table()

    ips_path = os.path.join(FILES, IPS_NAME)
    recs = read_ips(open(ips_path, 'rb').read())
    by_off = dict(recs)
    blob_at = CODE_AT
    hook = struct.unpack('<I', by_off[HOOK])[0]
    assert hook >> 26 == 0x25, 'the hook at main+0x2FACE0 is not a bl'
    target = HOOK + (((hook & 0x3FFFFFF) ^ 0x2000000) - 0x2000000) * 4
    assert target == TICK_NEXT or TABLE <= target < RO_START, f'the hook goes to main+{target:#x}: rebuild with build_v09.py first'
    tick_next = TICK_NEXT

    build = os.path.join(HERE, 'build')
    os.makedirs(build, exist_ok=True)
    obj, elf, binf = (os.path.join(build, n) for n in ('abilities.o', 'abilities.elf', 'abilities.bin'))
    run([tool('clang'), '-target', 'aarch64-none-elf', '-Os', '-std=gnu11', '-Wall', '-Wextra', '-Werror', '-ffreestanding',
         '-fno-builtin', '-fno-pic', '-fno-pie', '-fno-jump-tables', '-fno-stack-protector', '-fno-unwind-tables',
         '-fno-asynchronous-unwind-tables', '-mno-outline-atomics', '-ffunction-sections', '-I', HERE,
         '-c', os.path.join(HERE, 'abilities.c'), '-o', obj])
    bad = [l for l in run([tool('llvm-objdump'), '-r', obj]).splitlines()
           if 'R_AARCH64' in l and l.split()[1] not in PC_RELATIVE]
    assert not bad, 'relocations that depend on where main is loaded:\n' + '\n'.join(bad)
    script = os.path.join(build, 'abilities.ld')
    with open(script, 'w', newline='\n') as f:
        f.write('ENTRY(ability_entry)\n')
        for k, v in {**SYMBOLS, 'tick_next': tick_next, 'AZ_PACKED': AZ_AT}.items():
            f.write(f'{k} = {v:#x};\n')
        f.write(f'SECTIONS {{ . = {blob_at:#x}; .text : {{ *(.text .text.*) *(.rodata .rodata.*) }}\n'
                '  /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) *(.ARM.attributes) } }\n')
    run([tool('ld.lld'), '-T', script, '-nostdlib', '--no-undefined', '-o', elf, obj])
    sections = run([tool('llvm-objdump'), '-h', elf])
    for name in ('.data', '.bss', '.got'):
        assert f' {name} ' not in sections, f'{name} in the result: the code must not have writable data'
    run([tool('llvm-objcopy'), '-O', 'binary', '-j', '.text', elf, binf])
    blob = open(binf, 'rb').read()
    syms = run([tool('llvm-objdump'), '-t', elf])
    entry = next(int(l.split()[0], 16) for l in syms.splitlines() if l.endswith(' ability_entry'))
    assert blob_at + len(blob) <= CODE_END, f'the code is {len(blob)} bytes, {CODE_END - blob_at} fit'

    # everything this script placed before, and build_v09's table, goes; the code, the packed list and the hook come in
    recs = [(o, d) for o, d in recs if o != HOOK and not TABLE <= o < RO_START and not AZ_AT <= o < AZ_END]
    recs += [(HOOK, struct.pack('<I', bl(HOOK, entry))), (blob_at, blob), (AZ_AT, packed)]
    with open(ips_path, 'wb') as f:
        f.write(write_ips32(recs))

    for name in CHEATS:
        p = os.path.join(FILES, name)
        text = open(p, encoding='utf-8').read().replace('\r\n', '\n')
        parts = text.split('\n[')
        keep = [parts[0]] + ['[' + x for x in parts[1:] if not x.startswith(CHEAT_NAME + ']')]
        text = '\n'.join(keep).rstrip('\n') + '\n\n' + '\n'.join(CHEAT)
        new_base = f'78020000 {AZ_RAM - SELF_AT - 2:08X}'   # R2 = [base] + (AZ_RAM - SELF_AT - 2): the list in RAM
        assert text.count(OLD_CHEAT_BASE) + text.count(new_base) == 2, 'the cycle cheat\'s list address'
        text = text.replace(OLD_CHEAT_BASE, new_base)
        with open(p, 'w', newline='\r\n') as f:
            f.write(text)
    print(f'{count} Pokemon with an ability; A to Z list {n_az} packed into {len(packed)} bytes at main+{AZ_AT:#x}; '
          f'code {len(blob)} bytes at main+{blob_at:#x} (room {CODE_END - blob_at}), '
          f'entry main+{entry:#x}, then main+{tick_next:#x}')


if __name__ == '__main__':
    main()
